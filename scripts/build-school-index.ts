/**
 * Writes src/lib/school-files.generated.ts: one static import per
 * data/schools/*.json file. The app reads school data through it so the files
 * are compiled into the server bundle — a Cloudflare Worker has no filesystem
 * to read them from at request time. Runs before dev, build, typecheck and
 * test (package.json), so it always matches the directory; the output is
 * gitignored.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const names = readdirSync(join(root, 'data', 'schools'))
  .filter((name) => name.endsWith('.json'))
  .sort();

const source = [
  '// Generated by scripts/build-school-index.ts from data/schools/*.json; do not edit.',
  ...names.map((name, i) => `import s${i} from '../../data/schools/${name}';`),
  '',
  'export const SCHOOL_FILES: { path: string; json: unknown }[] = [',
  ...names.map((name, i) => `  { path: 'data/schools/${name}', json: s${i} },`),
  '];',
  '',
].join('\n');

writeFileSync(join(root, 'src', 'lib', 'school-files.generated.ts'), source);
